<?php

// config/cors.php
// السماح للـ Dashboard بالتواصل مع Laravel API

return [

    /*
    |--------------------------------------------------------------------------
    | المسارات التي تخضع لإعدادات CORS
    |--------------------------------------------------------------------------
    | api/* يشمل كل نقاط الـ API التي سيتواصل معها الـ Dashboard
    */
    'paths' => [
        'api/*',
        'sanctum/csrf-cookie',
    ],

    /*
    |--------------------------------------------------------------------------
    | HTTP Methods المسموح بها
    |--------------------------------------------------------------------------
    */
    'allowed_methods' => ['*'],

    /*
    |--------------------------------------------------------------------------
    | Origins المسموح بها
    |--------------------------------------------------------------------------
    | في التطوير نسمح لكل شيء من localhost
    | عند الإنتاج استبدل '*' بعنوان الـ Dashboard الفعلي
    */
    'allowed_origins' => array_values(array_filter(array_map(
        'trim',
        explode(',', env(
            'CORS_ALLOWED_ORIGINS',
            'http://localhost:8000,http://127.0.0.1:8000,http://localhost:5500,http://127.0.0.1:5500,http://localhost:5173,http://127.0.0.1:5173'
        ))
    ))),

    'allowed_origins_patterns' => [],

    /*
    |--------------------------------------------------------------------------
    | Headers المسموح بها
    |--------------------------------------------------------------------------
    | Authorization مهم جداً لأن Sanctum يرسل التوكن فيه
    */
    'allowed_headers' => ['*'],

    /*
    |--------------------------------------------------------------------------
    | Headers التي يمكن للـ Browser قراءتها من الرد
    |--------------------------------------------------------------------------
    */
    'exposed_headers' => [
        'Authorization',
        'X-RateLimit-Limit',
        'X-RateLimit-Remaining',
    ],

    /*
    |--------------------------------------------------------------------------
    | مدة الـ Cache للـ Preflight Request (بالثواني)
    |--------------------------------------------------------------------------
    */
    'max_age' => 3600,

    /*
    |--------------------------------------------------------------------------
    | السماح بإرسال الـ Cookies مع الطلبات
    |--------------------------------------------------------------------------
    */
    'supports_credentials' => true,

];
